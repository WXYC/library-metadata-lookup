async def test_returns_candidate_score_instances():
    """The harness expects ``list[CandidateScore]`` so the threshold sweep
    can mix this class's output with the variation / identity / close-pair
    classes."""
    pool = AsyncMock()
    pool.fetch = AsyncMock(
        side_effect=[
            [{"id": 42, "name": "Stereolab"}],
            [
                {
                    "typo": "Setreolab",
                    "canonical_id": 42,
                    "canonical_name": "Stereolab",
                    "top_id": 42,
                    "top_name": "Stereolab",
                    "top_score": 0.85,
                }
            ],
        ]
    )

    result = await fetch_positive_class_synthetic_typos(pool, n_artists=1, typos_per_artist=1)

    assert all(isinstance(r, CandidateScore) for r in result)
